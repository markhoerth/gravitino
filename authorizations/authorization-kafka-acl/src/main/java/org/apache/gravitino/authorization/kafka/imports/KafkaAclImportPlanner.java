package org.apache.gravitino.authorization.kafka.imports;

import com.google.common.collect.ImmutableList;
import java.util.ArrayList;
import java.util.Collection;
import java.util.Comparator;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.stream.Collectors;
import org.apache.gravitino.authorization.Privilege;
import org.apache.gravitino.authorization.kafka.KafkaAclProperties;
import org.apache.gravitino.authorization.kafka.KafkaAclTranslator;
import org.apache.gravitino.authorization.kafka.KafkaGrant;
import org.apache.gravitino.authorization.kafka.KafkaPrincipalResolver;
import org.apache.kafka.common.acl.AclBinding;
import org.apache.kafka.common.acl.AclOperation;
import org.apache.kafka.common.acl.AclPermissionType;
import org.apache.kafka.common.resource.PatternType;
import org.apache.kafka.common.resource.ResourcePattern;
import org.apache.kafka.common.resource.ResourceType;

/**
 * Plans a one-time import of existing Kafka ACLs into Gravitino Topic grants. Pure: no I/O.
 *
 * <p>"Implied" means exactly "regenerated by {@link KafkaAclTranslator} from the mapped grants", so
 * after the import the plugin's reconcile deletes none of the mapped or implied ACLs, and the ACLs
 * it does delete are exactly the unmapped ones under the principal prefix.
 */
public final class KafkaAclImportPlanner {

  private static final String ANY_HOST = "*";
  private static final String USER_TYPE = "User";

  /** Sorts ACLs by Principal, resource name and operation, then the remaining fields. */
  public static final Comparator<AclBinding> ACL_ORDER =
      Comparator.<AclBinding, String>comparing(b -> b.entry().principal())
          .thenComparing(b -> b.pattern().name())
          .thenComparing(b -> b.entry().operation())
          .thenComparing(b -> b.pattern().resourceType())
          .thenComparing(b -> b.pattern().patternType())
          .thenComparing(b -> b.entry().permissionType())
          .thenComparing(b -> b.entry().host());

  private KafkaAclImportPlanner() {}

  /**
   * Plans the import.
   *
   * @param acls every ACL on the cluster
   * @param props the plugin properties of the catalog (principal prefix and group template)
   * @param metalake the metalake name, used by the group prefix template
   * @param catalogTopics the topics of the catalog's {@code default} schema
   * @return the plan
   */
  public static ImportPlan plan(
      Collection<AclBinding> acls,
      KafkaAclProperties props,
      String metalake,
      Set<String> catalogTopics) {
    String principalPrefix = props.principalPrefix();
    KafkaAclTranslator translator = new KafkaAclTranslator(metalake, props.groupPrefixTemplate());

    List<UnmappedAcl> unmapped = new ArrayList<>();
    List<AclBinding> groupCandidates = new ArrayList<>();
    List<AclBinding> describeCandidates = new ArrayList<>();
    List<AclBinding> readWrite = new ArrayList<>();

    // Rules a-h, in order. DESCRIBE and group ACLs are decided once the grants are known.
    for (AclBinding acl : acls) {
      String principal = acl.entry().principal();
      ResourcePattern pattern = acl.pattern();
      UnmappedAcl.Reason reason = null;
      if (!USER_TYPE.equals(principalType(principal))) {
        reason = UnmappedAcl.Reason.NON_USER_PRINCIPAL;
      } else if (!principal.startsWith(principalPrefix)) {
        reason = UnmappedAcl.Reason.OUTSIDE_PRINCIPAL_PREFIX;
      } else if (!ANY_HOST.equals(acl.entry().host())) {
        reason = UnmappedAcl.Reason.HOST_RESTRICTED;
      } else if (pattern.resourceType() == ResourceType.GROUP) {
        if (pattern.patternType() == PatternType.PREFIXED
            && pattern.name().equals(translator.groupPrefix(principal))
            && acl.entry().operation() == AclOperation.READ
            && acl.entry().permissionType() == AclPermissionType.ALLOW) {
          groupCandidates.add(acl);
        } else {
          reason = UnmappedAcl.Reason.GROUP_NOT_PRINCIPAL_PREFIX;
        }
      } else if (pattern.resourceType() != ResourceType.TOPIC) {
        reason = UnmappedAcl.Reason.UNSUPPORTED_RESOURCE_TYPE;
      } else if (pattern.patternType() != PatternType.LITERAL
          || ResourcePattern.WILDCARD_RESOURCE.equals(pattern.name())) {
        reason = UnmappedAcl.Reason.NON_LITERAL_TOPIC_PATTERN;
      } else if (!catalogTopics.contains(pattern.name())) {
        reason = UnmappedAcl.Reason.TOPIC_NOT_IN_CATALOG;
      } else {
        switch (acl.entry().operation()) {
          case READ:
          case WRITE:
            readWrite.add(acl);
            break;
          case DESCRIBE:
            describeCandidates.add(acl);
            break;
          default:
            reason = UnmappedAcl.Reason.UNSUPPORTED_OPERATION;
        }
      }
      if (reason != null) {
        unmapped.add(new UnmappedAcl(acl, reason));
      }
    }

    // An ALLOW with a DENY on the same Principal, topic and operation has no effect in Kafka and
    // would not survive the plugin's DENY-over-ALLOW resolution.
    Set<String> denied =
        readWrite.stream()
            .filter(b -> b.entry().permissionType() == AclPermissionType.DENY)
            .map(KafkaAclImportPlanner::key)
            .collect(Collectors.toSet());
    List<MappedGrant> mapped = new ArrayList<>();
    for (AclBinding acl : readWrite) {
      boolean deny = acl.entry().permissionType() == AclPermissionType.DENY;
      if (!deny && denied.contains(key(acl))) {
        unmapped.add(new UnmappedAcl(acl, UnmappedAcl.Reason.SHADOWED_BY_DENY));
        continue;
      }
      Privilege.Name name =
          acl.entry().operation() == AclOperation.READ
              ? Privilege.Name.CONSUME_TOPIC
              : Privilege.Name.PRODUCE_TOPIC;
      mapped.add(
          new MappedGrant(
              KafkaPrincipalResolver.principalName(acl.entry().principal()),
              acl.pattern().name(),
              name,
              deny,
              acl));
    }

    Set<AclBinding> regenerated = translator.translate(toKafkaGrants(mapped));
    Set<AclBinding> existing = new HashSet<>(acls);
    List<AclBinding> implied = new ArrayList<>();
    Set<String> readWriteTopics =
        readWrite.stream().map(KafkaAclImportPlanner::principalTopic).collect(Collectors.toSet());
    for (AclBinding acl : groupCandidates) {
      if (regenerated.contains(acl)) {
        implied.add(acl);
      } else {
        unmapped.add(new UnmappedAcl(acl, UnmappedAcl.Reason.NOT_IMPLIED_BY_GRANT));
      }
    }
    for (AclBinding acl : describeCandidates) {
      if (regenerated.contains(acl)) {
        implied.add(acl);
      } else if (readWriteTopics.contains(principalTopic(acl))) {
        unmapped.add(new UnmappedAcl(acl, UnmappedAcl.Reason.NOT_IMPLIED_BY_GRANT));
      } else {
        unmapped.add(new UnmappedAcl(acl, UnmappedAcl.Reason.DESCRIBE_ONLY));
      }
    }
    Set<AclBinding> mappedSources =
        mapped.stream().map(MappedGrant::source).collect(Collectors.toSet());
    List<AclBinding> additions =
        regenerated.stream()
            .filter(b -> !existing.contains(b))
            .filter(b -> !mappedSources.contains(b))
            .collect(Collectors.toList());

    mapped.sort(Comparator.comparing(MappedGrant::source, ACL_ORDER));
    unmapped.sort(Comparator.comparing(UnmappedAcl::acl, ACL_ORDER));
    implied.sort(ACL_ORDER);
    additions.sort(ACL_ORDER);
    return new ImportPlan(mapped, unmapped, implied, additions);
  }

  /**
   * Converts mapped grants into the plugin's effective grant model.
   *
   * @param mapped the mapped grants
   * @return the grants as the plugin's grant source would report them after the import
   */
  public static List<KafkaGrant> toKafkaGrants(Collection<MappedGrant> mapped) {
    return mapped.stream()
        .map(
            g ->
                KafkaGrant.topic(
                    KafkaPrincipalResolver.USER_TYPE + g.gravitinoUser(),
                    g.topic(),
                    g.name(),
                    g.deny() ? KafkaGrant.Effect.DENY : KafkaGrant.Effect.ALLOW))
        .collect(ImmutableList.toImmutableList());
  }

  private static String principalType(String principal) {
    int idx = principal.indexOf(':');
    return idx < 0 ? "" : principal.substring(0, idx);
  }

  private static String principalTopic(AclBinding acl) {
    return acl.entry().principal() + "\u0000" + acl.pattern().name();
  }

  private static String key(AclBinding acl) {
    return principalTopic(acl) + "\u0000" + acl.entry().operation();
  }
}
